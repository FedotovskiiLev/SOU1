"""Materialize the closed CC0 drum dependency set under docs; no network/install."""
from pathlib import Path
import hashlib,json,shutil
root=Path(__file__).resolve().parents[1]
source=['LICENSE','tools/instruments/rack.mjs','tools/instruments/wav.mjs','tools/instruments/drum-kits.mjs','experiments/rack-browser/bank.mjs']
for directory in ['assets/cc0-mini','assets/fsa-electronic','assets/fsa-drums','assets/guigui-drums']:
    source += [p.relative_to(root).as_posix() for p in sorted((root/directory).rglob('*')) if p.is_file()]
allowed=set(source)|{'SOURCE_LOCK.json'}
existing=root/'docs/audio-kit'
if existing.exists():
    stale=[p.relative_to(existing).as_posix() for p in existing.rglob('*') if p.is_file() and p.relative_to(existing).as_posix() not in allowed]
    if stale:raise ValueError('Unexpected generated-package files; inspect before rebuilding: '+str(stale))
records=[]
for rel in sorted(source):
    src=root/rel
    if src.is_symlink():raise ValueError('No symlink assets: '+rel)
    dst=root/'docs/audio-kit'/rel;dst.parent.mkdir(parents=True,exist_ok=True);shutil.copyfile(src,dst)
    records.append({'path':rel,'sha256':hashlib.sha256(src.read_bytes()).hexdigest(),'bytes':src.stat().st_size})
lock={'schema':'sou1.web-drum-package.v1','codeLicense':'AGPL-3.0-only','sampleLicense':'CC0-1.0','files':records}
(root/'docs/audio-kit/SOURCE_LOCK.json').write_text(json.dumps(lock,indent=2)+'\n')
paths=['./audio-kit/'+r['path'] for r in records]+['./audio-kit/SOURCE_LOCK.json']
(root/'docs/drum-assets.js').write_text('// SPDX-License-Identifier: AGPL-3.0-only\n// Generated by tools/package-web-drums.py; do not edit by hand.\nself.SOU1_DRUM_ASSETS='+json.dumps(paths,separators=(',',':'))+';\n')
print('Packaged',len(records),'files,',sum(r['bytes'] for r in records),'bytes')
