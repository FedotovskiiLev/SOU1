"""Generate exact JS and Java registry from checked-in melodic manifests."""
import hashlib,json,pathlib,sys
CHECK=sys.argv[1:]==["--check"]
if sys.argv[1:] and not CHECK:raise SystemExit("Usage: generate-melodic-catalog.py [--check]")
def write(path,text):
 if CHECK:
  if path.read_text()!=text:raise SystemExit("Generated melodic catalog stale: "+str(path))
 else:path.write_text(text)
ROOT=pathlib.Path(__file__).resolve().parent.parent
q=json.dumps
presets=['chamber','chamber-flute','piano-room'];locks={};methods=[]
for preset in presets:
 raw=(ROOT/'docs/melodic-assets'/(preset+'.json')).read_bytes();m=json.loads(raw);h=hashlib.sha256(raw).hexdigest();locks[preset]={'bytes':len(raw),'sha256':h}
 samples=[]
 for s in m['samples']:
  b=(ROOT/'docs/melodic-assets'/s['file']).read_bytes()
  assert len(b)==s['bytes'] and hashlib.sha256(b).hexdigest()==s['sha256']
  samples.append('new SampleSpec('+','.join([q(s['file']),q(s['sha256']),str(s['bytes']),str(s['frames']),str(s['sampleRate']),str(s['rootNote']),str(s['loopStart']),str(s['loopEnd']),str(s['crossfade'])])+')')
 definitions=[]
 for d in m['instruments']:
  zones=['new LiveMelodicPool.Zone('+','.join(str(z[k]) for k in ['sampleIndex','keyLow','keyHigh','velocityLow','velocityHigh','gain'])+')' for z in d['zones']]
  definitions.append('new LiveMelodicPool.Instrument('+','.join(str(d[k]) for k in ['layer','gain','attack','release'])+',new LiveMelodicPool.Zone[]{'+','.join(zones)+'})')
 methods.append('case '+q(preset)+':return new Spec('+q(preset)+','+str(len(raw))+','+q(h)+',new SampleSpec[]{\n'+',\n'.join(samples)+'},new LiveMelodicPool.Instrument[]{\n'+',\n'.join(definitions)+'});')
write(ROOT/'docs/melodic-catalog.js','// SPDX-License-Identifier: AGPL-3.0-only\n// Generated by tools/generate-melodic-catalog.py.\nexport const MELODIC_ASSETS=Object.freeze('+json.dumps(locks,separators=(',',':'))+');\n')
java='''// SPDX-License-Identifier: AGPL-3.0-only
// Generated by tools/generate-melodic-catalog.py; do not edit.
package org.sou1.audio;
import org.sou1.audio.NativeMelodicBankLoader.SampleSpec;
import org.sou1.audio.NativeMelodicBankLoader.Spec;
final class NativeMelodicCatalog {
private NativeMelodicCatalog(){}
static Spec get(String preset){if(preset==null)throw new IllegalArgumentException("Melodic preset");switch(preset){
'''+ '\n'.join(methods)+'''\ndefault:throw new IllegalArgumentException("Unknown melodic preset");}}
}
'''
write(ROOT/'app/src/main/java/org/sou1/audio/NativeMelodicCatalog.java',java)
